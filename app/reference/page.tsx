/**
 * The worked example.
 *
 * Buyers of engineering work are asked to pay five figures for something they
 * have never seen. This page removes that: the actual deliverable, in full,
 * generated by the same engine on a synthetic hall — including the tables behind
 * it, so a sceptical engineer can check the arithmetic before spending anything.
 *
 * Everything here is regenerated by scripts/build-reference.sh and CI fails if the
 * committed files differ from a fresh run. A worked example that has drifted from
 * the engine is a promise we no longer keep.
 */

interface Pack {
  scenarios: {
    id: string;
    name: string;
    as_found: { racks: number; binding_name: string; basis: string };
    after_ladder: { racks: number };
    time_to_power: {
      weeks_to_full: number | null;
      sets_the_date: string;
      date_basis?: "none" | "assumed" | "supported";
      date_evidence_class?: string | null;
      date_binding_item?: string | null;
      date_label?: string;
    };
    economics: { capex_total_eur: { value: number } | null };
  }[];
  intake: { completeness: number; gaps: unknown[] };
}

async function readPack(): Promise<Pack | null> {
  try {
    const raw = await fs.readFile(
      path.join(process.cwd(), "public", "reference", "model_pack.json"),
      "utf8"
    );
    return JSON.parse(raw) as Pack;
  } catch {
    return null;
  }
}

interface CalibrationSnapshot {
  state: string;
  observations: number;
}

async function readCalibrationSnapshot(): Promise<CalibrationSnapshot | null> {
  try {
    const c = JSON.parse(await fs.readFile(path.join(process.cwd(), "public", "reference", "calibration.json"), "utf8")) as Partial<CalibrationSnapshot>;
    return typeof c.state === "string" && typeof c.observations === "number" ? { state: c.state, observations: c.observations } : null;
  } catch {
    return null;
  }
}

