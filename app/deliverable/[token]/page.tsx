export const dynamic = "force-dynamic";

export default async function DeliverablePage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = await params;
  const row = await getByToken(token);

  if (!row) {
    return (
      <Shell title="Not found">
        <p className="text-mute">
          This link does not correspond to an engagement. Check the address, or reply to the email
          it came in.
        </p>
      </Shell>
    );
  }

  if (row.status !== "released") {
    const waiting = row.status === "awaiting_intake";
    return (
      <Shell title={waiting ? "Waiting on your numbers" : "With the engineer"}>
        <p className="max-w-2xl text-mute">
          {waiting ? (
            <>
              Nothing has been produced yet because the hall&apos;s numbers have not been
              submitted.{" "}
              <Link href={`/intake/${token}`} className="text-power underline">
                Fill in the intake
              </Link>{" "}
              and the document follows.
            </>
          ) : (
            <>
              The document is generated and sits with a senior engineer for review. We do not
              publish an engineering opinion nobody has read. You will get an email the moment it
              is released.
            </>
          )}
        </p>
      </Shell>
    );
  }

  return (
    <main className="mx-auto w-full max-w-6xl px-5 pb-24 pt-24 sm:px-8">
      <div className="mb-6 flex flex-wrap items-center justify-between gap-3">
        <p className="font-mono text-[11px] uppercase tracking-[0.18em] text-verified">
          Released{row.released_at ? ` · ${new Date(row.released_at).toLocaleDateString()}` : ""}
        </p>
        <div className="flex flex-wrap items-center gap-3">
          {row.working_files?.[BOARD_HTML] ? (
            <a
              href={`/api/deliverable/${token}?format=board`}
              target="_blank"
              rel="noreferrer"
              className="rounded border border-power/60 px-4 py-2 text-sm font-semibold text-power hover:bg-power/10"
            >
              Board summary
            </a>
          ) : null}
          {row.deck_html ? (
            <a
              href={`/api/deliverable/${token}?format=deck`}
              target="_blank"
              rel="noreferrer"
              className="rounded border border-power/60 px-4 py-2 text-sm font-semibold text-power hover:bg-power/10"
            >
              Walkthrough deck
            </a>
          ) : null}
          <a
            href={`/api/deliverable/${token}?format=md`}
            className="rounded border border-line px-4 py-2 text-sm text-mute hover:text-ghost"
          >
            Download Markdown
          </a>
        </div>
      </div>
      {/* The document is generated by our own engine and stored as rendered HTML;
          it contains no scripts and no third-party content. */}
      <div
        className="rounded border border-line bg-white"
        dangerouslySetInnerHTML={{ __html: row.document_html ?? "" }}
      />
      {row.working_files && Object.keys(row.working_files).some((f) => !isPackFile(f)) ? (
        <section className="mt-8 rounded border border-line bg-panel-2 p-5">
          <p className="font-mono text-[10px] uppercase tracking-[0.14em] text-faint">
            Check our arithmetic
          </p>
          <p className="mt-2 max-w-3xl text-sm text-mute">
            The tables behind this document, as files your own engineers can open. Every headline
            quantity in <span className="font-mono text-ghost">provenance.csv</span> can be walked
            back to the assumptions underneath it. If you find an error, tell us — we would rather
            be corrected than cited.
          </p>
          <div className="mt-3 flex flex-wrap gap-2">
            {Object.keys(row.working_files)
              .filter((f) => !isPackFile(f))
              .sort()
              .map((f) => (
                <a
                  key={f}
                  href={`/api/deliverable/${token}?format=csv&file=${encodeURIComponent(f)}`}
                  className="rounded border border-line px-3 py-1.5 font-mono text-xs text-mute hover:text-ghost"
                >
                  {f}
                </a>
              ))}
          </div>
        </section>
      ) : null}
      {PRODUCT_BY_KIND[row.kind]?.endpoint === "spec" ? <SpecBasis intake={row.intake} files={row.working_files} /> : null}
      {row.kind === "proposal" ? null : <Provenance row={row} />}
      {/* A Procurement Specification is only two thirds delivered without this:
          its catalogue entry promises the comparison, and until now there was
          nowhere for the supplier responses to go. */}
      {PRODUCT_BY_KIND[row.kind]?.endpoint === "spec" && row.status === "released" ? (
        <BidComparison token={token} initial={priorComparison(row)} />
      ) : null}
      {row.kind === "proposal" ? null : (
        <>
          {/* A specification is already the next step; offering it under itself
              would be the page selling what the reader has just bought. */}
          {PRODUCT_BY_KIND[row.kind]?.endpoint === "spec" ? null : (
            <SpecUpsell constraint={bindingConstraint(row)} />
          )}
          <WatchUpsell />
        </>
      )}
    </main>
  );
}

/**
 * The constraint this document says binds, read out of the stored intake.
 *
 * Best effort and optional: the upsell reads correctly without it. Guessing a
 * constraint would be worse than not naming one, so an unreadable intake simply
 * returns null.
 */
function bindingConstraint(row: { intake?: unknown }): string | null {
  try {
    const meta = (row.intake as Record<string, unknown> | undefined)?.["_gridforge"];
    const t = (meta as Record<string, unknown> | undefined)?.["binding"];
    return typeof t === "string" && t.trim() ? t : null;
  } catch {
    return null;
  }
}

/**
 * A comparison already run for this engagement.
 *
 * Kept as a working file when it was produced, so reopening the page shows the
 * ranking rather than an empty upload box and a customer wondering whether it
 * worked. Unreadable means "none yet", never a guess.
 */
function priorComparison(row: { working_files?: Record<string, string> | null }) {
  const raw = row.working_files?.["bid_comparison.json"];
  if (!raw) return null;
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

type Meta = {
  endpoint?: string;
  generated_at?: string;
  provenance?: { engine_version?: string; code_sha256?: string | null; cost_library_sha256?: string | null; calibration_sha256?: string | null; read_at?: string } | null;
  review?: { by?: string | null; at?: string; pack_sha256?: string };
  spec?: { constraint?: string; relief?: string; sized_for_racks?: number };
};
const metaOf = (intake: unknown): Meta => ((intake as { _gridforge?: Meta } | null)?._gridforge ?? {}) as Meta;
const short = (h?: string | null) => (h ? `${h.slice(0, 12)}…` : null);

/**
 * Where this document came from, from what was recorded when it was generated and released. Nothing here is computed for
 * display: a field that was not recorded is said to be unrecorded rather than filled in.
 */
function Provenance({ row }: { row: { intake?: unknown; document_html?: string | null; working_files?: Record<string, string> | null; released_at?: string | null } }) {
  const m = metaOf(row.intake);
  const engine = m.provenance;
  return (
    <section className="mt-8 rounded border border-line bg-panel-2 p-5" aria-label="Provenance">
      <p className="font-mono text-[10px] uppercase tracking-[0.14em] text-faint">Provenance</p>
      <dl className="mt-2 grid max-w-3xl gap-x-6 gap-y-1 text-sm text-mute sm:grid-cols-[14rem_1fr]">
        <dt className="text-faint">Produced by</dt>
        <dd>
          {m.endpoint ? `the capacity engine, ${m.endpoint} endpoint` : "the capacity engine"}
          {m.generated_at ? `, generated ${new Date(m.generated_at).toLocaleDateString("en-IE")}` : ""}
        </dd>
        <dt className="text-faint">Engine build</dt>
        <dd>
          {engine?.engine_version
            ? `version ${engine.engine_version}; code ${short(engine.code_sha256) ?? "unrecorded"}, cost library ${short(engine.cost_library_sha256) ?? "unrecorded"}, calibration ${short(engine.calibration_sha256) ?? "unrecorded"} (read from the engine at generation)`
            : "not recorded for this document"}
        </dd>
        <dt className="text-faint">Document fingerprint</dt>
        <dd className="font-mono text-xs">sha256 {short(packHash({ document_html: row.document_html ?? null, working_files: row.working_files ?? null })) ?? "—"}</dd>
        <dt className="text-faint">Reviewed and released</dt>
        <dd>
          {m.review?.by ? `by ${m.review.by}` : "by a person; the reviewer's name was not recorded"}
          {m.review?.at ? ` on ${new Date(m.review.at).toLocaleDateString("en-IE")}` : row.released_at ? ` on ${new Date(row.released_at).toLocaleDateString("en-IE")}` : ""}
          {m.review?.pack_sha256 && m.review.pack_sha256 === packHash({ document_html: row.document_html ?? null, working_files: row.working_files ?? null }) ? ", and the text above is the text that was reviewed" : ""}
        </dd>
      </dl>
    </section>
  );
}

/**
 * The numbers a Procurement Specification was derived from, as the buyer gave them, and which of the site conditions were
 * NOT given and so rest on a library default. A duty quoted at a site condition nobody supplied is not quoted at "your"
 * site conditions, and the buyer is entitled to see which kind they have.
 */
type CarriedCondition = { id?: string; label?: string; status?: string; value?: number | null; text?: string | null; unit?: string | null; evidence?: string | null };
type CarriedAssumption = { label?: string; path?: string; unit?: string; assumed?: string };

/** The conditions and assumptions the ENGINE reported with the specification, if its result carried them; otherwise null. */
function carriedBasis(files: Record<string, string> | null | undefined): { conditions: CarriedCondition[]; assumed: CarriedAssumption[] } | null {
  try {
    const d = JSON.parse(files?.["specification.json"] ?? "null") as { site_conditions?: unknown; assumed_inputs?: unknown } | null;
    if (!d || !Array.isArray(d.site_conditions) || d.site_conditions.length === 0) return null;
    return { conditions: d.site_conditions as CarriedCondition[], assumed: Array.isArray(d.assumed_inputs) ? (d.assumed_inputs as CarriedAssumption[]) : [] };
  } catch {
    return null;
  }
}

function SpecBasis({ intake, files }: { intake: unknown; files?: Record<string, string> | null }) {
  const carried = carriedBasis(files);
  const doc = (intake ?? {}) as Record<string, any>;
  const m = metaOf(intake);
  const dry = doc?.site?.design_drybulb_C;
  const rows: [string, string][] = [
    ["Summer design dry bulb", typeof dry === "number" ? `${dry} °C (supplied by you)` : "not supplied — the engine used its library default for it. Quotations at a different site condition are not comparable: give suppliers the real figure."],
    ["Chilled-water supply", typeof doc?.thermal?.plant?.design_supply_C === "number" ? `${doc.thermal.plant.design_supply_C} °C (supplied by you)` : "not supplied"],
    ["Installed plant capacity", typeof doc?.thermal?.plant?.chilled_water_capacity_kW === "number" ? `${doc.thermal.plant.chilled_water_capacity_kW} kW (supplied by you)` : "not supplied"],
    ["Firm connection capacity", typeof doc?.grid?.firm_capacity_MVA === "number" ? `${doc.grid.firm_capacity_MVA} MVA (supplied by you)` : "not supplied"],
  ];
  return (
    <section className="mt-8 rounded border border-line bg-panel-2 p-5" aria-label="Basis of this specification">
      <p className="font-mono text-[10px] uppercase tracking-[0.14em] text-faint">Basis of this specification</p>
      <p className="mt-2 max-w-3xl text-sm text-mute">
        Every numeric requirement in it names the constraint of the capacity model it came from.
        {m.spec?.constraint ? ` It is written for one relief: ${m.spec.relief || m.spec.constraint}${m.spec.sized_for_racks ? `, sized for ${m.spec.sized_for_racks} racks` : ""}.` : ""}{" "}
        These are the site conditions it was derived from and where each came from.
      </p>
      {carried ? (
        <>
          <dl className="mt-3 grid max-w-3xl gap-x-6 gap-y-1 text-sm text-mute sm:grid-cols-[14rem_1fr]">
            {carried.conditions.map((c, i) => (
              <React.Fragment key={c.id ?? i}>
                <dt className="text-faint">{c.label ?? c.id}</dt>
                <dd>
                  {c.value !== null && c.value !== undefined ? `${c.value}${c.unit ? ` ${c.unit}` : ""}` : (c.text ?? "—")}
                  {c.evidence ? ` (evidence ${c.evidence})` : ""}
                  {c.status ? `: ${c.status.replace(/_/g, " ")}` : ""}
                </dd>
              </React.Fragment>
            ))}
          </dl>
          {carried.assumed.length ? (
            <>
              <p className="mt-3 max-w-3xl text-sm text-mute">Inputs that were assumed rather than supplied:</p>
              <ul className="mt-1 max-w-3xl list-disc pl-5 text-sm text-mute">
                {carried.assumed.map((a, i) => (
                  <li key={a.path ?? i}>{a.label ?? a.path}: not supplied, assumed {a.assumed}</li>
                ))}
              </ul>
            </>
          ) : null}
        </>
      ) : (
        <dl className="mt-3 grid max-w-3xl gap-x-6 gap-y-1 text-sm text-mute sm:grid-cols-[14rem_1fr]">
          {rows.map(([k, v]) => (
            <React.Fragment key={k}>
              <dt className="text-faint">{k}</dt>
              <dd>{v}</dd>
            </React.Fragment>
          ))}
        </dl>
      )}
    </section>
  );
}

function Shell({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <main className="mx-auto w-full max-w-3xl px-5 pb-24 pt-28 sm:px-8">
      <h1 className="text-2xl font-semibold text-ghost">{title}</h1>
      <div className="mt-4">{children}</div>
    </main>
  );
}
