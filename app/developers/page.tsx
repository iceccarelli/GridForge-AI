/**
 * The machine interface.
 *
 * The people who need this answer are increasingly not people. A colo operator's
 * portfolio team runs an agent over two hundred halls; a fund's diligence stack
 * wants the binding constraint before it bids. None of them will read a PDF.
 *
 * Everything rendered here comes from public/reference/tools.json, which is
 * generated by the engine itself and diffed in CI — so the schema an integrator
 * reads is the schema the engine publishes, not a hand-written copy of it
 * that drifted two releases ago. (The engine does not check a request against
 * that schema before it runs; the section on errors says what it does instead.)
 * The per-endpoint reference, the refusals, the retry rule and the browser policy
 * are generated from lib/openapi.ts and lib/api-reference.ts, the same data as
 * /openapi.json.
 */

interface Tool {
  name: string;
  description: string;
  endpoint: string;
  method: string;
  units: number;
  tier: string;
  returns: string;
  evidence_boundary?: string;
  inputSchema: Record<string, unknown>;
}

interface Catalogue {
  tools: Tool[];
  mcp: { endpoint: string; protocol: string; protocolVersion: string };
  auth: { header: string; note: string };
  evidence_note: string;
  rate_card?: { endpoint: string; units: number; tool: string | null }[];
}

interface Accuracy {
  state: string;
  statement: string;
  observations: number;
  sites: number;
  keys_asserted: number;
  keys_with_site_observations: number;
}

async function readJson<T>(file: string): Promise<T | null> {
  try {
    const raw = await fs.readFile(
      path.join(process.cwd(), "public", "reference", file),
      "utf8"
    );
    return JSON.parse(raw) as T;
  } catch {
    return null;
  }
}

