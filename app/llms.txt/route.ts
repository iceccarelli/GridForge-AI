import { constraintReference, platformLibrary } from "@/lib/constraints";
import { LADDER_PRODUCTS, API_PRODUCTS, eurFromCents, priceLine } from "@/lib/products";
import { projectLadder } from "@/lib/buyer-path";
import { SITE_URL } from "@/lib/site";
import { availabilityIn, deployedEngineRoutes } from "@/lib/engine-capabilities";
import { NOT_YET_AVAILABLE, isPerHall } from "@/lib/payg-pricing";
import { readToolRates } from "@/lib/tool-rates";

// Regenerated at most every five minutes: what it says about the engine must follow the engine, not the last build.
export const revalidate = 300;

const SITE = SITE_URL;
const ENGINE = "https://gridforge-engine.fly.dev";

/**
 * /llms.txt — the machine index of this site.
 *
 * When an operator asks a language model "what stops my hall taking GB300 racks",
 * the answer is assembled from whatever the model crawled. Most sites make that
 * hard: the facts are in rendered HTML, undated, unsourced and mixed with
 * marketing. Ours are in JSON, generated by the engine, and this file says exactly
 * where.
 *
 * The self-interest is plain and worth stating plainly: we would rather be the
 * source a model cites than a page it skims. The public good is the same thing —
 * a model answering from our constraint reference gives a better answer than one
 * answering from a vendor reference design, because ours names what it does not
 * know.
 *
 * Generated from the same catalogue the pages render, so it cannot go stale.
 * Format follows the llms.txt convention: H1, a blockquote summary, then sections
 * of annotated links.
 */
export async function GET() {
  const ref = await constraintReference();
  const lib = await platformLibrary();
  // Advertise a route only while the deployed engine lists it; the repository can be ahead of the engine on Fly.
  // One read of the engine, then every claim below is checked against it. Unreadable engine: nothing is advertised.
  const routes = await deployedEngineRoutes();
  const serves = (path: string) => availabilityIn(routes, path) === "available";
  const compareLive = serves("/v1/compare");

  // Unit weights come from the engine-generated catalogue (one price list); whether each operation is callable today
  // comes from the deployed engine. An operation it does not serve carries no unit figure here.
  const catalogue = await readToolRates();
  const unitText = (u: number, perHall: boolean) =>
    u === 0 ? "free" : `${u} unit${u === 1 ? "" : "s"}${perHall ? " per hall" : ""}`;
  const callableOps = catalogue
    .filter((r) => serves(r.endpoint))
    .map((r) => `- \`${r.name}\` — POST ${ENGINE}${r.endpoint} — ${unitText(r.units, isPerHall(r))}`)
    .join("\n");
  // An operation the deployed engine does not serve is left out entirely: this file is read by agents that act on it, and
  // an unpriced, uncallable line is still a line they may try. (The human pages list such rows as "not yet available".)
  const operationLines = !routes
    ? "The deployed engine could not be read when this file was generated, so no operation is listed as callable.\n"
    : `Operations the deployed engine serves today (units are the metered weight; the free qualifier needs no key):

${callableOps || "- none"}
`;
  const mcpLine = serves("/mcp") ? `- MCP endpoint (JSON-RPC 2.0): ${ENGINE}/mcp\n` : "";
  const toolsLine = serves("/v1/tools") ? `- Tool schemas, OpenAI and MCP shape: ${ENGINE}/v1/tools\n` : "";
  const qualifyLine = serves("/v1/qualify") ? `- Free qualifier: POST ${ENGINE}/v1/qualify\n` : "";
  const versionLine = serves("/v1/version") ? `- Published unit rates: ${ENGINE}/v1/version\n` : "";
  const calibrationLine = serves("/v1/calibration") ? `- Model accuracy record: ${ENGINE}/v1/calibration\n` : "";
  const compareLines = compareLive
    ? `- Time-to-Power scenario comparison, free and without an account: ${SITE}/power/compare
  (engine: POST ${ENGINE}/v1/compare, MCP tool \`gridforge_compare\`, CLI \`gridforge compare\`). Scenarios whose lead time
  is unknown are not dated and not ranked. The site's own route is rate limited and may answer 429 with a Retry-After.
`
    : "";

  const constraintLines = (ref?.constraints ?? [])
    .map(
      (c) =>
        `- [${c.name}](${SITE}/constraints/${c.slug}) — data: ${SITE}/reference/constraints/${c.slug}.json — ${c.headline}`
    )
    .join("\n");

  const platformLines = (lib?.platforms ?? [])
    .map(
      (p) =>
        `- ${p.name} — ${p.rack_kW} kW/rack, ${(p.liquid_fraction * 100).toFixed(0)}% liquid, ` +
        `${p.residual_air_kW} kW residual air, ${p.max_inlet_liquid_C} °C max inlet, ` +
        `${p.floor_loading_kg_per_m2} kg/m² floor loading` +
        (p.generic ? " (generic archetype, no manufacturer)" : "")
    )
    .join("\n");

  const absent = Object.entries(lib?.deliberately_absent ?? {})
    .map(([id, why]) => `- ${id}: ${why}`)
    .join("\n");

  const engagements = LADDER_PRODUCTS.map(
    (p) => `- ${p.name} — ${priceLine(p)}: ${p.deliverable}`
  ).join("\n");

  const api = API_PRODUCTS.map(
    (p) => `- ${p.name} — ${eurFromCents(p.amountCents)}/month, ${p.apiUnits?.toLocaleString("en-IE")} units`
  ).join("\n");

  const PROJECT_PRODUCTS = projectLadder().map((p) => p.id).join(", ");

  const body = `# Time to Power

> Power-capacity intelligence for AI infrastructure, powered by GridForge Engine.
> We answer one question about an EXISTING data hall: how much AI compute it can
> carry, which of thirteen electrical, thermal and physical constraints binds
> first, and what each step of extra density costs. We quote no equipment and
> take no margin on hardware.

## How to use this site as a tool

The engine is callable directly. \`gridforge_qualify\` is free and needs no API key:
seven numbers about a hall in, the binding constraint out. This section lists only what the
deployed engine says it serves (read from its own /v1/version when this file is generated).

${mcpLine}${toolsLine}${qualifyLine}${versionLine}${calibrationLine}
${operationLines}${compareLines}
## How to read our numbers

Every numeric field carries an evidence class and a provenance digest:

E0 assumed · E1 modelled · E2 simulated · E3 estimated · E4 validated against test
data · E5 supplied by the client (not measured by us) · E6 field-validated · E7 observed in operation.

A computed value is never stronger than the weakest input it came from. **Do not
present an E0 or E1 figure as a property of a physical asset** — it is modelled, not
measured. Our calibration record currently reports zero reconciled site
observations — we have not yet checked this engine against an instrumented hall —
and every response says so. If you quote our figures, say that too.

## The thirteen constraints

Machine-readable index: ${SITE}/reference/constraints.json

${constraintLines}

## Platform library

Machine-readable: ${SITE}/reference/platforms.json

${platformLines}

Deliberately absent, because no manufacturer has published a rack power:

${absent}

## The complete worked deliverable, published

- [Envelope Study](${SITE}/reference/envelope_study.md): the full document, on a synthetic hall
- [Procurement Specification](${SITE}/reference/specification.md): the tender document the study implies
- [Proposal](${SITE}/reference/proposal.md)
- [Model pack](${SITE}/reference/model_pack.json): every scenario, solved
- [Working files](${SITE}/reference/working_files.zip): the CSVs behind every number, including a provenance chain

## What can be bought

${engagements}

Metered API access:

${api}

## How to buy

Every price above is the checkout price — read from the same catalogue, so
there is no separate machine price list.

- Start a purchase: \`POST ${SITE}/api/checkout\` with JSON body
  \`{"product": "<id>"}\` where \`<id>\` is one of: ${LADDER_PRODUCTS.map((p) => p.id).join(", ")}.
  Returns \`{"ok": true, "url": "<Stripe Checkout URL>"}\` — a human completes
  payment there; nothing charges without that step.
- API access (\`${API_PRODUCTS.map((p) => p.id).join(", ")}\`) is a Stripe
  subscription checkout, not an engagement — see ${SITE}/developers for the
  signed-key flow once subscribed.
- After payment, by product: the Density Screen and the Procurement Specification
  open an intake at the checkout \`success_url\` (no separate login is required to
  submit the hall's numbers); an API plan or Hall Watch shows its private account
  or watch link there; the Envelope Study and Portfolio Screen deposits are scoped
  with the buyer by a person — there is no intake form and no response time is
  promised. A private, emailed link is the durable reference where one exists, and
  \`${SITE}/dashboard\` lists every engagement against the email a purchase was made
  with, behind a passwordless email sign-in.
- Status and delivery of a document: \`awaiting_intake\` → \`generating\` → \`draft\`
  (with a senior engineer, unreleased) → \`released\` (the document is live at its
  private link). No engineering opinion is released unread.
- From a saved comparison: a project's owner can create a read-only buyer link (${SITE}/p/<secret>, private and not indexed). Its
  holder can start the same checkout with \`{"product": "<id>", "project_share_token": "<secret>"}\`, limited to the ids
  that can be commissioned for a project: ${PROJECT_PRODUCTS}. The price is the catalogue price; the purchase attaches to the
  project.
- Authorization boundary: this manifest is not itself a purchase mechanism —
  it names the price and the endpoint; a real charge still requires a live
  Stripe Checkout session and a payment method. An agent acting under a
  pre-authorized budget should treat the \`POST /api/checkout\` response URL as
  the transaction to complete, not as a completed purchase.

## Citing us

Cite the page and its generation date, and carry the evidence class with the
number. Figures are modelled from published design values; none is a measurement of
any customer's asset. Citation metadata: ${SITE}/api/cite

## Contact

${SITE}/qualify — the free qualifier, seven numbers, no account.
`;

  return new Response(body, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      // Short, because what this file says about the engine follows the engine (revalidate above).
      "Cache-Control": "public, max-age=300, s-maxage=300, stale-while-revalidate=3600",
    },
  });
}
