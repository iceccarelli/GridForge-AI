export interface ProductPage {
  slug: string;
  productId: ProductId;
  /** The role that signs for the spend, in plain words. */
  buyer: string;
  /** The decision the deliverable informs. */
  decision: string;
  /** What we ask the buyer for. */
  inputs: string[];
  /** What the deliverable is not. */
  limits: string[];
  /** How the work reaches the buyer. */
  flow: string[];
  /** The search-result description: at most 160 characters (tests/site/metadata-limits.test.ts), and no price or duration, which the catalogue owns. */
  metaDescription: string;
  /**
   * The published sample of THIS deliverable (public/reference, generated by scripts/build-reference.sh), or null when none exists. A product
   * with no sample says so on its page; it is never pointed at another product's document as if it were its own.
   */
  sample: { href: string; label: string } | null;
  /** Where the sample shows the list of inputs still assumed (the data request the buyer is handed), when the deliverable includes one. */
  dataRequest?: { href: string; label: string };
}

