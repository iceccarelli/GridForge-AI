export function productPageBySlug(slug: string): ProductPage | undefined {
  return PRODUCT_PAGES.find((p) => p.slug === slug);
}

export function productForPage(page: ProductPage): Product {
  return PRODUCTS[page.productId];
}

/** The audience pages whose route through the offers includes this product, in the order the audiences are defined. */
export function audiencesForProduct(id: ProductId): Audience[] {
  return AUDIENCES.filter((a) => a.path.some((step) => step.kind === id));
}

/**
 * The turnaround as the page states it: always with its basis, because a count of days from the wrong starting point is a promise we do not make.
 * For a deposit it IS the sentence the deposit receipt and checkout state (depositTerms(kind).timing), not a second wording of it.
 */
export function turnaroundText(p: Product): string {
  const deposit = depositTerms(p.kind);
  if (deposit) return deposit.timing;
  if (p.recurring) return "Quarterly, and a re-run whenever you update an input";
  if (p.producesDeliverable) return `${p.turnaroundDays} working days, from a complete intake`;
  return `${p.turnaroundDays} working days`;
}

export interface BuyRow {
  label: string;
  text: string;
  link?: { href: string; label: string };
  /** A list under the text, for a row that is several statements. */
  items?: string[];
}

/**
 * The "Before you buy" facts for one product. Every row is read from something that proves it:
 *  - what you receive and the turnaround: the catalogue (lib/products.ts);
 *  - what we need: this page's own input list, and the sample where the deliverable includes a data request;
 *  - who reviews: app/api/admin/deliverables/route.ts refuses to release a document without `reviewed_by`, records it with the release and
 *    the deliverable page shows it to the buyer. That route releases documents generated by an engine endpoint (`endpoint` in the
 *    catalogue); a product with no endpoint (Hall Watch) is not claimed to be reviewed;
 *  - what it does not include: this page's `limits`;
 *  - terms: a plain link to /legal/terms. Checkout has no terms consent and that page is a template the owner has yet to finalise, so this
 *    page says nothing about what the terms provide or that a purchase is subject to them; no refund, tax or cancellation term is stated.
 */
export function beforeYouBuy(page: ProductPage): BuyRow[] {
  const p = productForPage(page);
  const rows: BuyRow[] = [
    { label: "You receive", text: p.deliverable },
    {
      label: "What we need from you",
      text: "The hall's numbers, listed below.",
      link: page.dataRequest ? { href: page.dataRequest.href, label: `See ${page.dataRequest.label}` } : { href: "#inputs-h", label: "See the list" },
    },
    { label: "Turnaround", text: turnaroundText(p) },
    page.sample
      ? { label: "Sample", text: `The ${page.sample.label} on a synthetic reference hall.`, link: { href: page.sample.href, label: "Read the sample" } }
      : { label: "Sample", text: "No sample of this document is published yet. The samples of the other engagements show the same engine and the same evidence classes.", link: { href: "/reference", label: "See the sample deliverables" } },
  ];
  if (p.endpoint) {
    rows.push({
      label: "Who reviews it",
      text:
        "A named engineer reviews each document before it is released to you. The name and date are recorded with the release and shown on your private deliverable page. " +
        "It is a review of screening-mode output, not an issued engineering opinion.",
    });
  }
  rows.push(
    { label: "Not included", text: "", items: page.limits },
    // A link and nothing more: the page asserts nothing about what the terms say or whether a purchase is bound by them.
    { label: "Terms", text: "", link: { href: "/legal/terms", label: "Read the terms" } },
  );
  return rows;
}
