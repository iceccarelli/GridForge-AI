import { spawn as nodeSpawn, execFileSync } from "node:child_process";
import fs from "node:fs";
import crypto from "node:crypto";
import { ObsError } from "./errors.mjs";

/**
 * Thin ffmpeg/ffprobe layer: binary discovery, encoding-config validation, argument builders, progress parsing, probing.
 * Argument builders are pure so the exact encoder arguments can be recorded in the manifest (with secrets redacted).
 *
 * @typedef {{ width: number, height: number, fps: number, videoBitrateKbps: number, audioBitrateKbps: number, gopSec: number, preset: string }} Encoding
 */

/** @type {Encoding} */
export const DEFAULT_ENCODING = Object.freeze({ width: 1280, height: 720, fps: 25, videoBitrateKbps: 2500, audioBitrateKbps: 64, gopSec: 2, preset: "veryfast" });

const PRESETS = ["ultrafast", "superfast", "veryfast", "faster", "fast", "medium"];

/** @param {Partial<Encoding>} [over] @returns {{ encoding: Encoding, errors: string[] }} */
export function resolveEncoding(over = {}) {
  const e = { ...DEFAULT_ENCODING, ...over };
  /** @type {string[]} */ const errors = [];
  const int = (/** @type {string} */ k, /** @type {number} */ lo, /** @type {number} */ hi) => {
    const v = /** @type {any} */ (e)[k];
    if (!Number.isInteger(v) || v < lo || v > hi) errors.push(`${k} must be an integer between ${lo} and ${hi}`);
  };
  int("width", 160, 3840); int("height", 90, 2160); int("fps", 1, 60);
  int("videoBitrateKbps", 100, 20000); int("audioBitrateKbps", 16, 320); int("gopSec", 1, 10);
  if (Number.isInteger(e.width) && e.width % 2) errors.push("width must be even (yuv420p)");
  if (Number.isInteger(e.height) && e.height % 2) errors.push("height must be even (yuv420p)");
  if (!PRESETS.includes(e.preset)) errors.push(`preset must be one of ${PRESETS.join(", ")}`);
  return { encoding: e, errors };
}

/** "1280x720" -> {width,height}; "2500k"/"2.5m"/"2500" -> kbps. */
export function parseSize(s) {
  const m = /^(\d{2,4})x(\d{2,4})$/.exec(String(s));
  if (!m) throw new ObsError("bad_option", `size must look like 1280x720 (got "${s}")`, { exitCode: 2 });
  return { width: Number(m[1]), height: Number(m[2]) };
}
export function parseBitrateKbps(s) {
  const m = /^(\d+(?:\.\d+)?)\s*([km]?)$/i.exec(String(s).trim());
  if (!m) throw new ObsError("bad_option", `bitrate must look like 2500k or 2.5m (got "${s}")`, { exitCode: 2 });
  const n = Number(m[1]);
  return Math.round(m[2].toLowerCase() === "m" ? n * 1000 : n);
}

/** x264 + AAC encode arguments shared by recordings and live output. Silent audio is generated by the caller's lavfi input. */
export function buildVideoArgs(enc) {
  const g = enc.fps * enc.gopSec;
  return [
    "-c:v", "libx264", "-preset", enc.preset, "-profile:v", "high", "-pix_fmt", "yuv420p",
    "-b:v", `${enc.videoBitrateKbps}k`, "-maxrate", `${enc.videoBitrateKbps}k`, "-bufsize", `${enc.videoBitrateKbps * 2}k`,
    "-g", String(g), "-keyint_min", String(g), "-sc_threshold", "0",
  ];
}
export function buildAudioArgs(enc) {
  return ["-c:a", "aac", "-b:a", `${enc.audioBitrateKbps}k`, "-ar", "44100", "-ac", "2"];
}
export function buildEncodeArgs(enc) {
  return [...buildVideoArgs(enc), ...buildAudioArgs(enc)];
}

/** The silent audio source every output carries (platforms reject video-only ingest). */
export function silentAudioInput(durationSec, { realtime = false } = {}) {
  // Live outputs need `-re` here: an unpaced lavfi source runs thousands of times faster than real time and starves the muxer of video.
  const a = realtime ? ["-re", "-f", "lavfi"] : ["-f", "lavfi"];
  if (durationSec) a.push("-t", String(durationSec));
  a.push("-i", "anullsrc=channel_layout=stereo:sample_rate=44100");
  return a;
}

/** Escape a path for use inside an ffmpeg filter argument (subtitles=filename=...). */
export function escapeFilterPath(p) {
  return String(p).replace(/\\/g, "\\\\").replace(/:/g, "\\:").replace(/'/g, "\\'").replace(/,/g, "\\,").replace(/\[/g, "\\[").replace(/\]/g, "\\]");
}

export const CAPTION_STYLE = "FontName=DejaVu Sans,FontSize=22,PrimaryColour=&H00FFFFFF,OutlineColour=&H99000000,BorderStyle=3,Outline=1,Shadow=0,MarginV=36";

/** @param {string} vttPath */
export function burnFilter(vttPath) {
  return `subtitles=filename=${escapeFilterPath(vttPath)}:force_style='${CAPTION_STYLE}'`;
}

/** @param {string|undefined} env value of an override @param {string[]} candidates @param {string} fallback */
function findBinary(env, candidates, fallback) {
  if (env) return env;
  for (const c of candidates) { try { fs.accessSync(c, fs.constants.X_OK); return c; } catch { /* next */ } }
  return fallback;
}
export const ffmpegPath = (env = process.env) => findBinary(env.OBS_FFMPEG, ["/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"], "ffmpeg");
export const ffprobePath = (env = process.env) => findBinary(env.OBS_FFPROBE, ["/usr/bin/ffprobe", "/usr/local/bin/ffprobe"], "ffprobe");

/** Throws a precondition error naming the missing tool. Returns the version line. */
export function requireFfmpeg(env = process.env) {
  try {
    const out = execFileSync(ffmpegPath(env), ["-hide_banner", "-version"], { encoding: "utf8", timeout: 10_000 });
    execFileSync(ffprobePath(env), ["-hide_banner", "-version"], { encoding: "utf8", timeout: 10_000 });
    return out.split("\n")[0];
  } catch {
    throw new ObsError("ffmpeg_missing", "ffmpeg/ffprobe could not be run", { exitCode: 2, hint: "Install ffmpeg (with libx264 and aac) or set OBS_FFMPEG / OBS_FFPROBE to the binaries." });
  }
}

/** Does this ffmpeg build offer the named protocol / encoder / filter? */
export function ffmpegHas(kind, name, env = process.env) {
  const flag = { protocol: "-protocols", encoder: "-encoders", filter: "-filters", muxer: "-muxers" }[kind];
  try {
    const out = execFileSync(ffmpegPath(env), ["-hide_banner", flag], { encoding: "utf8", timeout: 10_000 });
    return new RegExp(`(^|\\s)${name}(\\s|$)`, "m").test(out);
  } catch { return false; }
}

/**
 * Incremental parser for `-progress pipe:1` output (key=value lines, a block ends at progress=continue|end).
 * Emits normalised blocks; `bitrateKbps` is instantaneous (from total_size deltas over wall time) when available.
 */
export class ProgressParser {
  #buf = "";
  /** @type {Record<string,string>} */ #cur = {};
  #lastSize = null;
  #lastAt = null;
  /** @param {() => number} [now] */
  constructor(now = () => Date.now()) { this.now = now; }
  /** @param {string|Buffer} chunk @returns {{frame:number,totalSize:number|null,bitrateKbps:number|null,outTimeMs:number|null,speed:number|null,ended:boolean}[]} */
  feed(chunk) {
    this.#buf += chunk.toString();
    const out = [];
    let nl;
    while ((nl = this.#buf.indexOf("\n")) >= 0) {
      const line = this.#buf.slice(0, nl).trim();
      this.#buf = this.#buf.slice(nl + 1);
      const eq = line.indexOf("=");
      if (eq < 0) continue;
      const k = line.slice(0, eq); const v = line.slice(eq + 1);
      this.#cur[k] = v;
      if (k === "progress") {
        const c = this.#cur; this.#cur = {};
        const frame = Number(c.frame);
        const size = c.total_size && c.total_size !== "N/A" ? Number(c.total_size) : null;
        const at = this.now();
        let kbps = null;
        if (size !== null && this.#lastSize !== null && this.#lastAt !== null && at > this.#lastAt) kbps = ((size - this.#lastSize) * 8) / (at - this.#lastAt);
        if (size !== null) { this.#lastSize = size; this.#lastAt = at; }
        if (kbps === null && c.bitrate && /kbits/.test(c.bitrate)) kbps = parseFloat(c.bitrate);
        const us = c.out_time_us && c.out_time_us !== "N/A" ? Number(c.out_time_us) : null;
        out.push({
          frame: Number.isFinite(frame) ? frame : 0,
          totalSize: size,
          bitrateKbps: kbps,
          outTimeMs: us !== null && Number.isFinite(us) ? us / 1000 : null,
          speed: c.speed && /x/.test(c.speed) ? parseFloat(c.speed) : null,
          ended: v === "end",
        });
      }
    }
    return out;
  }
}

/**
 * Probe a media file. Frame count is decoded (-count_frames), not trusted from container metadata.
 * @param {string} file
 */
export function probeMedia(file, env = process.env) {
  let raw;
  try {
    raw = execFileSync(ffprobePath(env), ["-v", "error", "-count_frames", "-show_streams", "-show_format", "-of", "json", file], { encoding: "utf8", maxBuffer: 16 * 1024 * 1024, timeout: 60_000 });
  } catch (e) {
    throw new ObsError("probe_failed", `ffprobe could not read ${file}: ${/** @type {Error} */ (e).message.split("\n")[0]}`);
  }
  const j = JSON.parse(raw);
  /** @type {any[]} */ const streams = j.streams ?? [];
  const v = streams.find((s) => s.codec_type === "video");
  const a = streams.find((s) => s.codec_type === "audio");
  const subs = streams.filter((s) => s.codec_type === "subtitle");
  const fr = (/** @type {string} */ s) => { const [n, d] = String(s ?? "0/1").split("/").map(Number); return d ? n / d : 0; };
  return {
    formatName: j.format?.format_name,
    durationSec: Number(j.format?.duration ?? 0),
    bytes: Number(j.format?.size ?? 0),
    video: v ? { codec: v.codec_name, profile: v.profile, width: v.width, height: v.height, pixFmt: v.pix_fmt, fps: fr(v.avg_frame_rate), frames: Number(v.nb_read_frames ?? v.nb_frames ?? 0), durationSec: Number(v.duration ?? 0) } : null,
    audio: a ? { codec: a.codec_name, sampleRate: Number(a.sample_rate), channels: a.channels, durationSec: Number(a.duration ?? 0) } : null,
    subtitles: subs.map((s) => ({ codec: s.codec_name, language: s.tags?.language ?? null })),
  };
}

/** @param {string} file */
export function sha256File(file) {
  const h = crypto.createHash("sha256");
  const fd = fs.openSync(file, "r");
  try {
    const buf = Buffer.alloc(1 << 20);
    for (let n; (n = fs.readSync(fd, buf, 0, buf.length, null)) > 0;) h.update(buf.subarray(0, n));
  } finally { fs.closeSync(fd); }
  return h.digest("hex");
}

/**
 * Run ffmpeg to completion (finite jobs: transcode, slate generation, HLS packaging).
 * @param {string[]} args
 * @param {{ spawn?: typeof nodeSpawn, env?: Record<string, string | undefined>, signal?: AbortSignal, onProgress?: (p: any) => void, track?: Set<import("node:child_process").ChildProcess>, stdin?: (w: import("node:stream").Writable) => Promise<void> }} [opts]
 */
export function runFfmpeg(args, opts = {}) {
  const spawn = opts.spawn ?? nodeSpawn;
  const full = ["-hide_banner", ...(opts.stdin ? [] : ["-nostdin"]), "-loglevel", "error", "-nostats", "-progress", "pipe:1", ...args];
  return new Promise((resolve, reject) => {
    const child = spawn(ffmpegPath(opts.env), full, { stdio: [opts.stdin ? "pipe" : "ignore", "pipe", "pipe"] });
    opts.track?.add(child);
    const parser = new ProgressParser();
    let tail = "";
    child.stdout?.on("data", (d) => { for (const p of parser.feed(d)) opts.onProgress?.(p); });
    child.stderr?.on("data", (d) => { tail = (tail + d.toString()).slice(-4000); });
    const onAbort = () => { child.kill("SIGKILL"); };
    opts.signal?.addEventListener("abort", onAbort, { once: true });
    child.on("error", (e) => { opts.track?.delete(child); reject(new ObsError("ffmpeg_spawn", `ffmpeg could not start: ${e.message}`, { exitCode: 2 })); });
    child.on("close", (code, sig) => {
      opts.track?.delete(child);
      opts.signal?.removeEventListener("abort", onAbort);
      if (code === 0) resolve({ code, args: full });
      else reject(new ObsError("ffmpeg_failed", `ffmpeg exited with ${sig ?? code}: ${tail.trim().split("\n").slice(-3).join(" | ")}`, { details: { args: full } }));
    });
    if (opts.stdin && child.stdin) {
      child.stdin.on("error", () => { /* ffmpeg died early: the close handler reports why */ });
      opts.stdin(child.stdin).catch((e) => { child.kill("SIGKILL"); reject(e); });
    }
  });
}
